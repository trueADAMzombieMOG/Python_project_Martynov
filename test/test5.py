#Составить функцию решения задачи: из заданного числа вычли сумму его цифр. Из
#результата вновь вычли сумму его цифр и т. д. Через сколько таких действий
#получится нуль?

def sum_digits(num):
    """Возвращает сумму цифр числа."""
    s = 0
    while num > 0:
        s += num % 10      # последняя цифра
        num //= 10         # убираем последнюю цифру
    return s


def steps_to_zero(n):
    """Считает, через сколько вычитаний суммы цифр получится 0."""
    count = 0
    while n > 0:
        n = n - sum_digits(n)
        count += 1
    return count


number = int(input("Введите число: "))
print("Количество действий:", steps_to_zero(number))
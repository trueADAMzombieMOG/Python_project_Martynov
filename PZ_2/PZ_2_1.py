# дано трехзначное число. Используя одну операцию деления нацело, вывести первую цифру данного числа.
n = input("Введите трехзначное число: ")
while type(n) != int:
    try:
        n = int(n)
    except ValueError:
        print("Неправильно ввели! Нужно целое число.")
        n = input("Введите трехзначное число: ")
else:
    if 100 <= abs(n) <= 999:
        print("результат =", n // 100)
    else:
        print("Ошибка: число не является трехзначным!")